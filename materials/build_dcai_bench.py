"""build_dcai_bench.py - the Python reference for the data-edit bench.

Two jobs, one file:
  1. build  : make the seeded split and the declared label-noise plant from the real UCI
              digits (sklearn.datasets.load_digits), and write assets/dcai-sample.js with json.dumps.
  2. ladder : run every rung of the bench with an independent implementation of the SAME frozen
              model (k-nearest neighbours, k = 10, squared Euclidean distance on the integer pixels)
              and the same confident-learning detector, and write materials/bench-canon-python.json.

The browser engine (assets/dcai-live.js) must reproduce every flag to the row and every accuracy
to the test item. Everything is integer arithmetic, so agreement is exact or it is a bug.

Usage:
  python3 materials/build_dcai_bench.py build            # writes the sample (seed below)
  python3 materials/build_dcai_bench.py ladder           # runs the ladder on the shipped sample
  python3 materials/build_dcai_bench.py sweep 20         # ladder over 20 seeds, for the spread
"""
import json
import sys
from pathlib import Path

import numpy as np
from sklearn.datasets import load_digits

ROOT = Path(__file__).resolve().parent.parent
SWEEP_BASE = 20210904  # the day the Data-Centric AI Competition closed; the sweep runs 20 seeds from here
SEED = 20210921  # the shipped seed: of those 20, the one whose ladder sits closest to the 20-seed mean
K = 10
FOLDS = 4
N_TEST, N_TRAIN = 500, 800  # the other 497 rows are the "more data" pool
# the declared plant: (true digit, given digit) -> share of that true digit flipped
PLANT = {(1, 7): 0.35, (7, 1): 0.25, (3, 8): 0.30, (8, 3): 0.20, (4, 9): 0.35, (9, 4): 0.25}
POOL = 2.0  # flips are drawn at random from the 2m items of the digit that look most like the target
AMBIG_MAX_VOTES = 5  # "ambiguous": no neighbour majority, top class holds 5 or fewer of 10 votes
DIGITS = "0123456789abcdefg"  # pixel value 0..16 as one character


# ---------------------------------------------------------------- build

def make_sample(seed):
    d = load_digits()
    X = d.data.astype(np.int64)
    y = d.target.astype(int)
    rng = np.random.default_rng(seed)
    perm = rng.permutation(len(y))
    te, tr, ex = perm[:N_TEST], perm[N_TEST:N_TEST + N_TRAIN], perm[N_TEST + N_TRAIN:]
    cent = np.array([X[y == c].mean(0) for c in range(10)])

    def plant(ids):
        given = y[ids].copy()
        for (a, b), r in PLANT.items():
            cand = np.array([i for i, t in enumerate(ids) if y[t] == a])
            m = int(round(r * len(cand)))
            s = np.array([((X[ids[i]] - cent[b]) ** 2).sum() - ((X[ids[i]] - cent[a]) ** 2).sum() for i in cand])
            order = cand[np.argsort(s, kind="stable")]
            top = order[: int(np.ceil(POOL * m))]
            pick = rng.choice(top, m, replace=False)
            given[pick] = b
        return given

    g_tr = plant(tr)
    g_ex = plant(ex)
    folds = np.arange(N_TRAIN) % FOLDS
    rng.shuffle(folds)
    folds_ex = np.arange(len(ex)) % FOLDS
    rng.shuffle(folds_ex)
    folds = np.concatenate([folds, folds_ex])

    rows = []
    for part, ids, giv in (("test", te, y[te]), ("train", tr, g_tr), ("extra", ex, g_ex)):
        for j, i in enumerate(ids):
            rows.append({"part": part, "uci": int(i), "px": "".join(DIGITS[v] for v in X[i]),
                         "y": int(y[i]), "g": int(giv[j])})
    return {"seed": seed, "k": K, "folds": [int(f) for f in folds], "rows": rows}


def write_sample(sample):
    parts = {p: [r for r in sample["rows"] if r["part"] == p] for p in ("test", "train", "extra")}
    out = {
        "seed": sample["seed"],
        "source": "UCI Optical Recognition of Handwritten Digits (Alpaydin and Kaynak, 1998), "
                  "the 1,797-image copy shipped as sklearn.datasets.load_digits",
        "plant": [{"from": a, "to": b, "rate": r} for (a, b), r in PLANT.items()],
        "plantRule": "for each pair, round(rate x count) items of the true digit are relabelled, drawn at "
                     "random from the 2m that look most like the target digit (distance to its class mean)",
        "folds": sample["folds"],
    }
    for p, rs in parts.items():
        out[p] = {"px": [r["px"] for r in rs], "y": [r["y"] for r in rs], "g": [r["g"] for r in rs],
                  "uci": [r["uci"] for r in rs]}
    head = ("/* dcai-sample.js - the data-edit bench sample, generated by materials/build_dcai_bench.py.\n"
            " * All 1,797 real images of the UCI Optical Recognition of Handwritten Digits test copy\n"
            " * (sklearn.datasets.load_digits; Alpaydin and Kaynak 1998; UCI, CC BY 4.0), 8x8, pixels 0-16\n"
            " * written one character each ('0'-'9','a'-'g'). y = true digit, g = the label the training\n"
            " * set was given after the declared plant. The test set is never relabelled. Seed %d. */\n"
            % sample["seed"])
    (ROOT / "assets" / "dcai-sample.js").write_text(head + "window.DCAI_SAMPLE = " + json.dumps(out, separators=(",", ":")) + ";\n")


def read_sample():
    txt = (ROOT / "assets" / "dcai-sample.js").read_text()
    js = txt[txt.index("window.DCAI_SAMPLE = ") + len("window.DCAI_SAMPLE = "):].rstrip().rstrip(";")
    return json.loads(js)


# ---------------------------------------------------------------- the frozen model

def decode(pxs):
    return np.array([[DIGITS.index(c) for c in s] for s in pxs], dtype=np.int64)


def shift(img, dx, dy):
    a = img.reshape(8, 8)
    out = np.zeros_like(a)
    for r in range(8):
        for c in range(8):
            rr, cc = r - dy, c - dx
            if 0 <= rr < 8 and 0 <= cc < 8:
                out[r, c] = a[rr, cc]
    return out.reshape(64)


def knn(Xtr, ytr, Xq):
    """votes (n x 10) and predictions. Distance ties go to the lower training index; vote ties
    go to whichever tied class appears first among the neighbours, nearest first."""
    D = ((Xq[:, None, :] - Xtr[None, :, :]) ** 2).sum(-1)
    idx = np.argsort(D, axis=1, kind="stable")[:, :K]
    V = np.zeros((len(Xq), 10), dtype=np.int64)
    pred = np.zeros(len(Xq), dtype=int)
    for r in range(len(Xq)):
        for j in idx[r]:
            V[r, ytr[j]] += 1
        m = V[r].max()
        for j in idx[r]:
            if V[r, ytr[j]] == m:
                pred[r] = ytr[j]
                break
    return V, pred


def oos_votes(X, g, folds, in_sample=False):
    if in_sample:
        V, _ = knn(X, g, X)
        return V
    V = np.zeros((len(X), 10), dtype=np.int64)
    for f in range(FOLDS):
        a, b = folds != f, folds == f
        Vb, _ = knn(X[a], g[a], X[b])
        V[b] = Vb
    return V


def confident_learning(V, g):
    """Northcutt, Jiang and Chuang 2021, eqs. 1-2, in integer form: p_j = V_j / K and
    t_j = S_j / (K n_j), so p_j >= t_j  <=>  V_j * n_j >= S_j. Collisions go to the largest p;
    a tie that includes the given label keeps the given label, else the lowest digit."""
    n = np.array([(g == j).sum() for j in range(10)])
    S = np.array([V[g == j, j].sum() for j in range(10)])
    flag = np.zeros(len(g), dtype=bool)
    sug = g.copy()
    joint = np.zeros((10, 10), dtype=np.int64)
    for r in range(len(g)):
        cand = [l for l in range(10) if n[l] > 0 and V[r, l] * n[l] >= S[l]]
        if not cand:
            continue
        m = max(V[r, l] for l in cand)
        best = [l for l in cand if V[r, l] == m]
        js = g[r] if g[r] in best else best[0]
        joint[g[r], js] += 1
        if js != g[r]:
            flag[r] = True
            sug[r] = js
    return flag, sug, joint, S, n


def argmax_flags(V, g):
    """the baseline CL compares against: flag whenever the out-of-sample argmax disagrees."""
    flag = np.zeros(len(g), dtype=bool)
    for r in range(len(g)):
        m = V[r].max()
        top = [l for l in range(10) if V[r, l] == m]
        flag[r] = g[r] not in top
    return flag


def detector_stats(flag, planted):
    tp = int((flag & planted).sum())
    return {"flagged": int(flag.sum()), "caught": tp, "planted": int(planted.sum()),
            "precision_pct": round(100 * tp / max(1, int(flag.sum())), 1),
            "recall_pct": round(100 * tp / int(planted.sum()), 1)}


def per_class(pred, truth):
    return [int((pred[truth == c] == c).sum()) for c in range(10)], [int((truth == c).sum()) for c in range(10)]


CONFIGS = [dict(pool=pool, fix=fix, ambig=amb, aug=aug, leak=leak)
           for pool in ("base", "more") for fix in ("none", "remove", "relabel")
           for amb in (False, True) for aug in (False, True) for leak in (False, True)]


def config_id(c):
    return "%s-%s-%s-%s-%s" % (c["pool"], c["fix"], "amb" if c["ambig"] else "x",
                               "aug" if c["aug"] else "x", "leak" if c["leak"] else "oos")


def unpack(s):
    Xte, yte = decode(s["test"]["px"]), np.array(s["test"]["y"])
    Xtr = np.vstack([decode(s["train"]["px"]), decode(s["extra"]["px"])])
    ytr = np.concatenate([s["train"]["y"], s["extra"]["y"]]).astype(int)
    gtr = np.concatenate([s["train"]["g"], s["extra"]["g"]]).astype(int)
    folds = np.array(s["folds"])
    return Xte, yte, Xtr, ytr, gtr, folds


def evaluate(s, c, cache=None):
    """one bench configuration, end to end. Rows 0..799 are the base training set, 800..1296 the pool
    of 497 more rows carrying the same plant. The test set is only ever scored."""
    Xte, yte, Xall, yall, gall, fall = cache or unpack(s)
    n = N_TRAIN if c["pool"] == "base" else len(gall)
    X, y, g, folds = Xall[:n], yall[:n], gall[:n].copy(), fall[:n]
    planted = g != y
    V = oos_votes(X, g, folds, in_sample=c["leak"])
    flag, sug, joint, S, cnt = confident_learning(V, g)
    det = detector_stats(flag, planted)
    det["relabel_right"] = int((sug[flag] == y[flag]).sum())
    det["argmax"] = detector_stats(argmax_flags(V, g), planted)
    keep = np.ones(n, dtype=bool)
    lab = g.copy()
    if c["fix"] == "remove":
        keep &= ~flag
    elif c["fix"] == "relabel":
        lab = sug.copy()
    dropped = 0
    if c["ambig"]:
        amb = keep & (V.max(1) <= AMBIG_MAX_VOTES)
        dropped = int(amb.sum())
        keep &= ~amb
    Xk, gk, fk = X[keep], lab[keep], folds[keep]
    info = {"weakest": None, "aug_rows": 0}
    if c["aug"]:
        # weakest digit by out-of-sample agreement on the EDITED training set, never the test set
        Vk = oos_votes(Xk, gk, fk)
        agree = [[int((Vk[gk == d].argmax(1) == d).sum()), int((gk == d).sum())] for d in range(10)]
        w = 0
        for d in range(1, 10):
            if agree[d][0] * agree[w][1] < agree[w][0] * agree[d][1]:
                w = d
        src = np.where(gk == w)[0]
        aug = [shift(Xk[i], dx, dy) for i in src for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
        Xk = np.vstack([Xk, np.array(aug)])
        gk = np.concatenate([gk, np.full(len(aug), w)])
        info = {"weakest": w, "aug_rows": len(aug), "agree": agree}
    _, pred = knn(Xk, gk, Xte)
    ok, tot = per_class(pred, yte)
    return {"id": config_id(c), "config": c, "train_rows": int(len(Xk)), "correct": int((pred == yte).sum()),
            "test": int(len(yte)), "acc_pct": round(100 * float((pred == yte).mean()), 1),
            "per_class_correct": ok, "per_class_total": tot,
            "wrong_label_rows_left": int(((gk[:keep.sum()] != y[keep])).sum()),
            "planted": int(planted.sum()), "detector": det, "ambiguous_dropped": dropped,
            "flagged_rows": [int(i) for i in np.where(flag)[0]], **info}


def ladder(s):
    cache = unpack(s)
    Xte, yte, Xall, yall, gall, fall = cache
    ref_X, ref_y = Xall[:N_TRAIN], yall[:N_TRAIN]
    _, pred = knn(ref_X, ref_y, Xte)
    out = {"seed": s["seed"], "k": K, "folds": FOLDS,
           "reference_true_labels": {"correct": int((pred == yte).sum()), "acc_pct": round(100 * float((pred == yte).mean()), 1)},
           "planted_by_pair": {f"{a}->{b}": int(((yall[:N_TRAIN] == a) & (gall[:N_TRAIN] == b)).sum()) for (a, b) in PLANT},
           "configs": {}}
    for c in CONFIGS:
        r = evaluate(s, c, cache)
        out["configs"][r["id"]] = r
    return out


KEY = ["base-none-x-x-oos", "more-none-x-x-oos", "base-remove-x-x-oos", "base-relabel-x-x-oos",
       "base-relabel-amb-x-oos", "base-relabel-x-aug-oos", "base-relabel-x-x-leak", "more-relabel-x-x-oos"]


def main():
    cmd = sys.argv[1] if len(sys.argv) > 1 else "ladder"
    if cmd == "build":
        write_sample(make_sample(SEED))
        print("wrote assets/dcai-sample.js", (ROOT / "assets" / "dcai-sample.js").stat().st_size, "bytes")
    elif cmd == "ladder":
        out = ladder(read_sample())
        (ROOT / "materials" / "bench-canon-python.json").write_text(json.dumps(out, indent=1))
        print("reference", out["reference_true_labels"])
        for k in KEY:
            r = out["configs"][k]
            print(f'{r["acc_pct"]:5.1f} {r["correct"]}/{r["test"]} rows {r["train_rows"]:5d} {k} det {r["detector"]["precision_pct"]}/{r["detector"]["recall_pct"]} flagged {r["detector"]["flagged"]} left {r["wrong_label_rows_left"]}')
    elif cmd == "sweep":
        n = int(sys.argv[2]) if len(sys.argv) > 2 else 20
        res = []
        for i in range(n):
            smp = make_sample(SWEEP_BASE + i)
            s = sample_view(smp)
            o = ladder(s)
            row = [o["reference_true_labels"]["acc_pct"]] + [o["configs"][k]["acc_pct"] for k in KEY]
            row += [o["configs"]["base-remove-x-x-oos"]["detector"]["precision_pct"], o["configs"]["base-remove-x-x-oos"]["detector"]["recall_pct"],
                    o["configs"]["base-remove-x-x-leak"]["detector"]["recall_pct"]]
            res.append(row)
            print(smp["seed"], row, flush=True)
        a = np.array(res)
        (ROOT / "materials" / "bench-sweep-python.json").write_text(json.dumps({"seeds": n, "columns": ["reference"] + KEY + ["cl_precision", "cl_recall", "leak_recall"], "rows": res}, indent=1))
        print("mean", a.mean(0).round(2).tolist())
        base = a[:, 1]
        for j, name in enumerate(["reference"] + KEY):
            dlt = a[:, j] - base
            print(f"{name:26s} mean {a[:, j].mean():.2f} delta {dlt.mean():+.2f} min {dlt.min():+.1f} max {dlt.max():+.1f} worse-than-base {int((dlt < 0).sum())}/{n}")


def sample_view(smp):
    parts = {p: [r for r in smp["rows"] if r["part"] == p] for p in ("test", "train", "extra")}
    s = {"seed": smp["seed"], "folds": smp["folds"]}
    for p, rs in parts.items():
        s[p] = {"px": [r["px"] for r in rs], "y": [r["y"] for r in rs], "g": [r["g"] for r in rs]}
    return s


if __name__ == "__main__":
    main()
